#!/usr/bin/env python3
"""
export_headers.py - write the real motion examples (and the grader's reference ranges) as plain C++17 header files you can commit.

  python tools/export_headers.py                                  # -> include/motion/*.hpp   (6 best clips per action, 15 fps, <= 4 s each: about 1.5 MB in total)
  python tools/export_headers.py --out /tmp/hdr --clips 12 --fps 30 --max-secs 6        # bigger
  python tools/export_headers.py --actions sit stand walk         # only these actions (the index header then lists only those)

Files written (all generated: do not edit by hand, re-run this instead)
  nerva_motion_core.hpp        the types and decoding helpers (ActionSet, decode_clip ...), no dependencies beyond <cstdint>/<vector>
  nerva_motion_<action>.hpp    one per action: the example clips of that action as int16 data  (sit, stand, walk, run, jump, crouch, ...)
  nerva_motion_profiles.hpp    the grader's per-action reference ranges (typical / tolerable range, weight, median of every measure)
  nerva_motion.hpp             include this one: pulls in everything and gives you  nerva::motion::kActions[]  and  nerva::motion::find("sit")

Data format: an action vector is 30 numbers per frame in the engine's layout (pelvis xyz yaw | footL xyz yaw contact | footR xyz yaw contact | handL xyz on |
handR xyz on | look xyz on | torso xyz on). Stored as int16 = value x 1000 (metres -> mm, radians -> mrad wrapped to +-pi, flags 0/1 -> 0/1000). decode_clip() gives
floats back (yaw unwrapped). Every clip starts at the origin facing +Z, y up, x = the body's left, 1.0 = engine-sized skeleton (leg 0.87 m).
Which clips: per action the clips the grader rates as the most typical, one performer at a time in turn, so the set is varied, not twelve takes of one person.
Source: CMU Graphics Lab Motion Capture Database (mocap.cs.cmu.edu), BVH conversion by B. Hahne (cgspeed); credit them. Each header says which trial every clip is.
"""
import argparse, math, os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import get_real_motions, motion_features as mf, motion_grader as G

COLS = 30


def pick(prof, F, act, perf, action, k):
    """Indices of k clips of `action`: highest typicality score, taking one per performer in turn."""
    idx = [i for i in range(len(act)) if act[i] == action]; sc = {}
    for i in idx:
        r = G.grade_features(F[i], action, prof)
        sc[i] = r["score"] if r["score"] is not None else -1
    by = {}
    for i in sorted(idx, key=lambda i: -sc[i]):
        by.setdefault(perf[i], []).append(i)
    order = sorted(by, key=lambda p: -sc[by[p][0]]); out = []
    while len(out) < k and any(by.values()):
        for p in order:
            if by[p] and len(out) < k:
                out.append(by[p].pop(0))
    return out


def encode(clip, step, max_frames):
    c = clip[::step]
    if len(c) > max_frames:
        s = (len(c) - max_frames) // 2; c = c[s:s + max_frames]
    c = get_real_motions.canonical(c.astype(np.float64))             # the cropped clip must start at the origin facing +Z again
    c[:, [3, 7, 12]] = (c[:, [3, 7, 12]] + np.pi) % (2 * np.pi) - np.pi
    q = np.rint(c * 1000.0)                                         # yaw stays wrapped here; decode_clip() unwraps it
    if np.abs(q).max() > 32000:
        raise ValueError("value out of int16 range after scaling")
    return q.astype(np.int16)


def wrap_lines(vals, per=COLS):
    return ",\n".join("    " + ",".join(str(int(v)) for v in vals[i:i + per]) for i in range(0, len(vals), per))


CORE = r'''// GENERATED by tools/export_headers.py - do not edit by hand.
// Real motion-capture examples in the NERVA action layout. See tools/export_headers.py for the format.
// Data: CMU Graphics Lab Motion Capture Database (mocap.cs.cmu.edu), BVH conversion by B. Hahne (cgspeed).
#pragma once
#include <cstdint>
#include <cmath>
#include <vector>

namespace nerva { namespace motion {

inline constexpr int kActionDim = 30;   // pelvis xyz yaw | footL xyz yaw contact | footR xyz yaw contact | handL xyz on | handR xyz on | look xyz on | torso xyz on

struct ActionSet {
    const char* name;                   // "sit", "stand", "walk" ...
    const char* group;                  // "locomotion", "posture", "activity", "dance"
    const char* about;                  // one line description
    int clips;                          // number of example clips
    int fps;                            // frames per second of the stored clips
    const int16_t* frames;              // frames[c] = number of frames of clip c
    const int16_t* values;              // all clips concatenated, kActionDim values per frame, value x 1000
    const char* const* source;          // source[c] = which CMU trial clip c comes from
};

// Total frames of the set, and the frame index where clip c starts.
inline int total_frames(const ActionSet& s) { int n = 0; for (int c = 0; c < s.clips; ++c) n += s.frames[c]; return n; }
inline int clip_start(const ActionSet& s, int c) { int n = 0; for (int i = 0; i < c; ++i) n += s.frames[i]; return n; }

// Decode clip c to floats: out has frames[c] * kActionDim floats (metres, radians, flags 0/1). Yaw channels are unwrapped so they never jump by 2*pi.
inline void decode_clip(const ActionSet& s, int c, std::vector<float>& out) {
    const int n = s.frames[c]; const int16_t* v = s.values + (size_t)clip_start(s, c) * kActionDim;
    out.resize((size_t)n * kActionDim);
    for (int f = 0; f < n; ++f)
        for (int k = 0; k < kActionDim; ++k) {
            float x = v[(size_t)f * kActionDim + k] * 0.001f;
            if (k == 8 || k == 13 || k == 17 || k == 21 || k == 25 || k == 29) x = x > 0.5f ? 1.0f : 0.0f;     // contact / on flags
            out[(size_t)f * kActionDim + k] = x;
        }
    const float pi = 3.14159265358979f;
    for (int k : {3, 7, 12})
        for (int f = 1; f < n; ++f) {
            float& cur = out[(size_t)f * kActionDim + k]; const float prev = out[(size_t)(f - 1) * kActionDim + k];
            while (cur - prev > pi) cur -= 2 * pi;
            while (cur - prev < -pi) cur += 2 * pi;
        }
}

}}  // namespace nerva::motion
'''


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default="include/motion"); ap.add_argument("--real", default=G.REAL_DEFAULT); ap.add_argument("--actions", nargs="+")
    ap.add_argument("--clips", type=int, default=6, help="clips per action"); ap.add_argument("--fps", type=int, default=15, choices=(10, 15, 30)); ap.add_argument("--max-secs", type=float, default=4.0)
    a = ap.parse_args(); prof, z, F = G.get_profiles(a.real); os.makedirs(a.out, exist_ok=True)
    A, off, dt = z["actions"], z["offsets"], float(z["dt"]); act = z["action"]; perf = z["performer"]; lab = z["labels"]; desc = z["description"]
    step = max(1, int(round(1.0 / (a.fps * dt)))); fps = int(round(1.0 / (dt * step))); maxf = int(round(a.max_secs * fps))
    import motion_actions as MA; meta = {x.name: x for x in MA.ACTIONS}
    names = [n for n in prof.names if not a.actions or n in a.actions]
    if not names:
        sys.exit("no such action; known: " + ", ".join(prof.names))
    written = []; sets = []
    def write(name, text):
        path = os.path.join(a.out, name); open(path, "w").write(text); written.append((name, os.path.getsize(path)))
    write("nerva_motion_core.hpp", CORE)
    for n in names:
        ids = pick(prof, F, act, perf, n, a.clips); clips = [encode(A[off[i]:off[i + 1]], step, maxf) for i in ids]
        if not clips:
            continue
        src = [f"{lab[i]}: {desc[i]}"[:90].replace("\\", "/").replace('"', "'") for i in ids]; ns = f"data_{n}"
        about = meta[n].about if n in meta else n; group = meta[n].group if n in meta else "activity"
        body = ["// GENERATED by tools/export_headers.py - do not edit by hand. Real CMU motion capture, see nerva_motion_core.hpp for the format.", "#pragma once", '#include "nerva_motion_core.hpp"', "",
                f"namespace nerva {{ namespace motion {{ namespace {ns} {{", "",
                f"inline constexpr int16_t kFrames[{len(clips)}] = {{{', '.join(str(len(c)) for c in clips)}}};",
                "inline constexpr const char* kSource[] = {"] + [f'    "{s}",' for s in src] + ["};", "",
                f"// {len(clips)} clips, {sum(len(c) for c in clips)} frames at {fps} fps, {COLS} values per frame (value x 1000)",
                "inline constexpr int16_t kValues[] = {", wrap_lines(np.concatenate(clips).reshape(-1)), "};", "",
                f'inline constexpr ActionSet kSet = {{"{n}", "{group}", "{about}", {len(clips)}, {fps}, kFrames, kValues, kSource}};', "", "}}}  // namespace nerva::motion::" + ns, ""]
        write(f"nerva_motion_{n}.hpp", "\n".join(body)); sets.append(n)
    # profiles
    def fl(x):                                                      # a valid C++ float literal: "2" must become "2.0f", never "2f"
        if not np.isfinite(x):
            return "std::numeric_limits<float>::quiet_NaN()"
        t = f"{x:.6g}"
        return (t if any(ch in t for ch in ".e") else t + ".0") + "f"
    K = len(mf.NAMES)
    pr = ["// GENERATED by tools/export_headers.py - do not edit by hand.", "// The realism grader's reference ranges: per action and per body measure, what real performers do (see tools/motion_grader.py).",
          "// typ = range where a clip earns full credit, tol = range where it earns part credit (zero outside), w = how much the measure tells this action from others.",
          "#pragma once", "#include <limits>", "", "namespace nerva { namespace motion {", "", f"inline constexpr int kFeatureCount = {K};",
          "inline constexpr const char* kFeatureNames[kFeatureCount] = {" + ", ".join(f'"{x}"' for x in mf.NAMES) + "};",
          "inline constexpr const char* kFeatureUnits[kFeatureCount] = {" + ", ".join(f'"{mf.UNIT[x]}"' for x in mf.NAMES) + "};", "",
          "struct Profile { const char* action; int real_clips; float med[kFeatureCount]; float typ_lo[kFeatureCount]; float typ_hi[kFeatureCount]; float tol_lo[kFeatureCount]; float tol_hi[kFeatureCount]; float w[kFeatureCount]; };", "",
          "inline constexpr Profile kProfiles[] = {"]
    for n in sets:
        p = prof.p[n]; arr = lambda v: "{" + ", ".join(fl(x) for x in v) + "}"
        pr.append(f'    {{"{n}", {p["n"]}, {arr(p["med"])},\n     {arr(p["typ"][:, 0])},\n     {arr(p["typ"][:, 1])},\n     {arr(p["tol"][:, 0])},\n     {arr(p["tol"][:, 1])},\n     {arr(p["w"])}}},')
    pr += ["};", f"inline constexpr int kProfileCount = {len(sets)};", "", "}}  // namespace nerva::motion", ""]
    write("nerva_motion_profiles.hpp", "\n".join(pr))
    idx = ["// GENERATED by tools/export_headers.py - do not edit by hand.", "// Include this header: it pulls in every example set and the grader profiles.", "//   for (const auto& s : nerva::motion::kActions) { ... s.name, s.clips ... }",
           '//   const nerva::motion::ActionSet* sit = nerva::motion::find("sit");', "#pragma once", '#include "nerva_motion_core.hpp"', '#include "nerva_motion_profiles.hpp"']
    idx += [f'#include "nerva_motion_{n}.hpp"' for n in sets] + ["#include <cstring>", "", "namespace nerva { namespace motion {", "",
            f"inline constexpr int kActionCount = {len(sets)};", "inline constexpr ActionSet kActions[kActionCount] = {"] + [f"    data_{n}::kSet," for n in sets] + ["};", "",
            "inline const ActionSet* find(const char* name) { for (const auto& s : kActions) if (std::strcmp(s.name, name) == 0) return &s; return nullptr; }", "", "}}  // namespace nerva::motion", ""]
    write("nerva_motion.hpp", "\n".join(idx))
    tot = sum(s for _, s in written); print(f"wrote {len(written)} headers to {a.out}  ({tot / 1e6:.2f} MB; {len(sets)} actions, {a.clips} clips each at {fps} fps, <= {a.max_secs:g} s)")
    for nme, sz in written:
        print(f"  {nme:34s}{sz / 1024:9.1f} KB")
    print(f"\nuse it:   #include \"motion/nerva_motion.hpp\"   (compile with -I{os.path.dirname(a.out.rstrip('/')) or '.'})")


if __name__ == "__main__":
    main()
